export function getRoutineShortTitle(routine?: { id?: string; title?: string; shortTitle?: string } | null): string {
  if (!routine) return 'Workout';
  if (routine.shortTitle) return routine.shortTitle;
  const id = routine.id || '';
  if (id === 'workout-a') return 'Workout A';
  if (id === 'workout-b') return 'Workout B';
  if (id === 'workout-c') return 'Workout C';
  const title = routine.title || '';
  const match = title.match(/^(Workout\s+[A-Z0-9]+)/i);
  if (match) return match[1];
  return title;
}
